#!/usr/bin/env bash
# xray-remove.sh - remove the 3x-ui panel (extension xray-3xui) and leave the rest
# of the stack (nginx + decoy site, other extensions) running.
#
# Self-contained: bash, docker with the compose plugin, iproute2; no network.
# Reads data/xray-3xui/state.env. Run as root.
#
#   xray-remove.sh [--yes] [--purge]
#
# Removes, in this order: the nginx routes (the panel location, the http-level
# snippet with the server blocks of the "plain" name, the TLS front routes of the
# whitelist SNI and the plain name; reload), the certificate registration of the
# plain name (no more renewals), the container, its network and image, the outway
# rules (IPv4 and IPv6), the sysctl.d file and the systemd units, the entry in
# data/extensions.compose.yml. Without --purge data/xray-3xui/ (state with the
# password and the keys, the panel database, the saved image) and the certificate
# files of the plain name are kept, so a reinstall restores the same panel and
# links; --purge deletes them and the standalone scripts of this extension.
#
# Environment: XRAY_STATE (state file), XRAY_DRY_RUN=1 (outway commands are only
# printed).
set -Eeuo pipefail

SELF="$(readlink -f "${BASH_SOURCE[0]}")"
HERE="$(dirname "$SELF")"
STATE_FILE="${XRAY_STATE:-@STATE_FILE@}"
if [[ "$STATE_FILE" == "@STATE_FILE@" ]]; then
    STATE_FILE="$HERE/../../data/xray-3xui/state.env"
fi
STATE_FILE="$(readlink -m "$STATE_FILE")"
X_DIR="$(dirname "$STATE_FILE")"
LOC_ID="xray-3xui"
SERVICE="xui"
YES=0
PURGE=0

say() { printf '%s\n' "$*" >&2; }
info() { say "    $*"; }
warn() { say "warning: $*"; }
die() {
    say "error: $*"
    exit 1
}

state_get() {
    [[ -f "$STATE_FILE" ]] || return 0
    sed -n "s/^$1=//p" "$STATE_FILE" | tail -n1
}

outway() {
    if [[ -f "$HERE/xray-outway.sh" ]]; then
        XRAY_STATE="$STATE_FILE" bash "$HERE/xray-outway.sh" "$@"
    else
        TGPROXY_STATE="$STATE_FILE" TGPROXY_DRY_RUN="${XRAY_DRY_RUN:-0}" bash "$HERE/../telegram-web-proxy/tgproxy-outway.sh" "$@"
    fi
}

compose() {
    env -i -C "$APP_DIR" \
        "PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin" \
        "HOME=${HOME:-/root}" "LANG=C.UTF-8" "TERM=${TERM:-dumb}" \
        docker compose "$@"
}

# unregister_compose: drop this extension's entry of data/extensions.compose.yml
# (same format as install.sh ext_unregister_compose; `services: {}` when empty).
unregister_compose() {
    local f="$APP_DIR/data/extensions.compose.yml" line tmp i
    local -a ids=() paths=()
    [[ -f "$f" ]] || return 0
    while IFS= read -r line || [[ -n "$line" ]]; do
        if [[ "$line" =~ ^[[:space:]]*-[[:space:]]+\"(.*)\"[[:space:]]+#[[:space:]]+([a-z0-9][a-z0-9_-]*)$ ]]; then
            [[ "${BASH_REMATCH[2]}" != "$LOC_ID" ]] || continue
            paths+=("${BASH_REMATCH[1]}")
            ids+=("${BASH_REMATCH[2]}")
        fi
    done <"$f"
    tmp="$(mktemp "$f.XXXXXX")"
    if ((${#ids[@]})); then
        {
            printf '# Generated by install.sh (ext_register_compose): do not edit.\ninclude:\n'
            for i in "${!ids[@]}"; do
                printf '  - "%s" # %s\n' "${paths[i]}" "${ids[i]}"
            done
        } >"$tmp"
    else
        printf 'services: {}\n' >"$tmp"
    fi
    chmod 644 "$tmp"
    mv -f "$tmp" "$f"
}

while (($#)); do
    case "$1" in
        -y | --yes) YES=1 ;;
        --purge) PURGE=1 ;;
        -h | --help)
            sed -n '2,/^set -E/p' "$SELF" | sed '$d; s/^# \{0,1\}//'
            exit 0
            ;;
        *) die "unknown argument '$1' (see --help)" ;;
    esac
    shift
done

[[ "${XRAY_DRY_RUN:-0}" == 1 ]] || ((EUID == 0)) || die "must run as root (try: sudo $0)"
[[ -f "$STATE_FILE" ]] || die "state file not found: $STATE_FILE (nothing to remove?)"
APP_DIR="$(state_get APP_DIR)"
NET_NAME="$(state_get NET_NAME)"
IMAGE="$(state_get XUI_IMAGE)"
PROJECT="$(state_get COMPOSE_PROJECT)"
SCRIPTS_DIR="$(state_get SCRIPTS_DIR)"
PROJECT="${PROJECT:-escape}"
PLAIN_NAME="$(state_get PLAIN_DOMAIN)"
[[ -d "$APP_DIR" && -f "$APP_DIR/docker-compose.yml" ]] || die "APP_DIR '$APP_DIR' from the state file is not an escape project"

if ((!YES)); then
    [[ -t 0 ]] || die "no terminal: pass --yes to confirm"
    what="container, image, outway rules, nginx routes"
    ((!PURGE)) || what+=", panel database, password and keys${PLAIN_NAME:+, certificate of $PLAIN_NAME}"
    read -r -p "Remove the 3x-ui panel ($what)? [y/N] " ans || die "no input"
    [[ "${ans,,}" == y || "${ans,,}" == yes ]] || die "aborted"
fi

have_docker=0
command -v docker >/dev/null 2>&1 && docker info >/dev/null 2>&1 && have_docker=1
((have_docker)) || warn "docker is not available: skipping the container, network and image"

say "==> nginx routes"
NGX="${APP_DIR:?}/data/nginx"
rm -f "$NGX/locations.d/${LOC_ID:?}.conf" "$NGX/servers.d/${LOC_ID:?}.conf" "$NGX/servers.d/${LOC_ID:?}.conf.in" "$NGX/stream.d/${LOC_ID:?}.map"
if ((have_docker)) && [[ -n "$(compose ps -q nginx 2>/dev/null | head -n1)" ]]; then
    if compose exec -T nginx nginx -t >/dev/null 2>&1; then
        compose exec -T nginx nginx -s reload >/dev/null 2>&1 && info "nginx reloaded: the panel path now goes to the decoy site, the whitelist SNI and the plain name to the site"
    else
        warn "nginx -t fails after removing the routes: $(compose exec -T nginx nginx -t 2>&1 | tail -n1)"
    fi
fi

# The certificate registration of data/nginx/extra-certs.list (format of install.sh
# ext_cert_request): the entry of this extension goes away, the others stay.
if [[ -f "$NGX/extra-certs.list" ]]; then
    tmp="$(mktemp "$NGX/extra-certs.list.XXXXXX")"
    { grep -v "^$LOC_ID " "$NGX/extra-certs.list" || true; } >"$tmp"
    chmod 644 "$tmp"
    mv -f "$tmp" "$NGX/extra-certs.list"
    info "certificate registration of '$LOC_ID' removed (no more renewals)"
fi
if ((PURGE)) && [[ -n "$PLAIN_NAME" && "$PLAIN_NAME" != "$DOMAIN" && "$PLAIN_NAME" =~ ^[A-Za-z0-9.-]+$ ]]; then
    say "==> certificate of $PLAIN_NAME"
    # Another extension may use the same name: then the files stay.
    if ! grep -q " $PLAIN_NAME\$" "$NGX/extra-certs.list" 2>/dev/null; then
        if ! { ((have_docker)) && compose run --rm -T certbot delete --cert-name "$PLAIN_NAME" --non-interactive >/dev/null 2>&1; }; then
            rm -rf "${APP_DIR:?}/data/letsencrypt/live/${PLAIN_NAME:?}" "${APP_DIR:?}/data/letsencrypt/archive/${PLAIN_NAME:?}" "${APP_DIR:?}/data/letsencrypt/renewal/${PLAIN_NAME:?}.conf"
        fi
        rm -rf "${NGX:?}/selfsigned/${PLAIN_NAME:?}"
        info "deleted the certificate files of $PLAIN_NAME"
    else
        info "the certificate of $PLAIN_NAME is registered by another extension: kept"
    fi
fi

if ((have_docker)); then
    say "==> 3x-ui container, network, image"
    compose rm -sf "$SERVICE" >/dev/null 2>&1 || true
    # Fallback when the compose file is already unregistered or broken.
    cids="$(docker ps -aq --filter "label=com.docker.compose.project=$PROJECT" --filter "label=com.docker.compose.service=$SERVICE" 2>/dev/null || true)"
    # shellcheck disable=SC2086
    [[ -z "$cids" ]] || docker rm -f $cids >/dev/null 2>&1 || true
    [[ -z "$NET_NAME" ]] || docker network rm "$NET_NAME" >/dev/null 2>&1 || warn "network $NET_NAME was not removed (in use or already gone)"
    [[ -z "$IMAGE" ]] || docker rmi "$IMAGE" >/dev/null 2>&1 || info "image $IMAGE was not removed (in use or already gone)"
fi

say "==> outway rules and systemd units"
outway remove-unit || warn "removing the systemd units failed"
outway down || warn "removing the outway rules failed"

say "==> compose registration"
unregister_compose
rm -f "${X_DIR:?}/installed"
info "entry '$LOC_ID' removed from $APP_DIR/data/extensions.compose.yml"

if ((PURGE)); then
    say "==> deleting the state, the panel database and the scripts"
    [[ "$X_DIR" == */data/xray-3xui ]] || die "refusing to delete suspicious path '$X_DIR'"
    rm -rf "${X_DIR:?}"
    info "deleted $X_DIR"
    # The installed copies (not the ones of the repository) go away too.
    if [[ -n "$SCRIPTS_DIR" && -d "$SCRIPTS_DIR" ]] &&
        [[ "$SCRIPTS_DIR" == "$APP_DIR/scripts" || "$SCRIPTS_DIR" == */xray-3xui ]]; then
        rm -f "${SCRIPTS_DIR:?}/xray-remove.sh" "${SCRIPTS_DIR:?}/xray-config.sh" "${SCRIPTS_DIR:?}/xray-outway.sh"
        rmdir "$SCRIPTS_DIR" 2>/dev/null || true
        info "deleted the scripts in $SCRIPTS_DIR"
    fi
else
    info "kept: $X_DIR (state with the password and the keys, panel database, saved image); delete it with --purge"
fi
say "Removed. nginx, the decoy site and the other extensions keep running."
