# lib/certs.sh - TLS certificates: temporary self-signed, Let's Encrypt via certbot, renewal timer.
# Sourced by install.sh (see the source list there): functions and variable
# defaults only, nothing runs at source time.
# shellcheck shell=bash
#
# Besides the certificate of DOMAIN, extensions may register certificates of
# their own names (ext_cert_request ID NAME / ext_cert_release ID [--delete]).
# Registered names are listed in data/nginx/extra-certs.list ("<id> <name>" per
# line); `renew` renews them too and issues the ones still missing.

RENEW_UNIT="fakeapp-certbot-renew"
RENEW_CRON=/etc/cron.d/fakeapp-certbot
EXT_CERTS_FILE="$NGINX_DATA/extra-certs.list"

# ensure_selfsigned DOMAIN [DIR]: temporary certificate so that nginx can start
# before Let's Encrypt has issued the real one (kept while it matches DOMAIN).
# DIR defaults to data/nginx/selfsigned (the one of DOMAIN of .env).
ensure_selfsigned() {
    local domain=$1 dir="${2:-$NGINX_DATA/selfsigned}"
    mkdir -p "$dir"
    if [[ -s "$dir/fullchain.pem" && -s "$dir/privkey.pem" ]] &&
        openssl x509 -in "$dir/fullchain.pem" -noout -checkhost "$domain" 2>/dev/null | grep -q 'does match'; then
        return 0
    fi
    openssl req -x509 -newkey rsa:2048 -nodes -days 3650 -subj "/CN=$domain" \
        -addext "subjectAltName=DNS:$domain" \
        -keyout "$dir/privkey.pem" -out "$dir/fullchain.pem" 2>/dev/null ||
        die "$(t certs.selfsigned_fail)"
    chmod 600 "$dir/privkey.pem"
    info "$(t certs.selfsigned_ok "$domain")"
}

# have_le_cert DOMAIN: a Let's Encrypt certificate for DOMAIN exists.
have_le_cert() {
    [[ -s "$LE_DIR/live/$1/fullchain.pem" && -s "$LE_DIR/live/$1/privkey.pem" ]]
}

# certbot_issue DOMAIN: a Let's Encrypt certificate for DOMAIN (certificate
# name = DOMAIN) via the one-shot certbot container (webroot; port 80 of this
# stack answers the challenge for every name). Returns 1 with hints on failure.
certbot_issue() {
    local domain=$1 email
    email="$(env_get "$APP_DIR/.env" LE_EMAIL)"
    local -a args=(certonly --webroot -w /var/www/acme -d "$domain" --cert-name "$domain"
        --non-interactive --agree-tos --keep-until-expiring)
    if [[ -n "$email" ]]; then
        args+=(--email "$email" --no-eff-email)
    else
        args+=(--register-unsafely-without-email)
    fi
    [[ "$(env_or_default LE_STAGING 0)" != 1 ]] || {
        args+=(--staging)
        warn "$(t certs.staging_warn)"
    }
    info "$(t certs.requesting "$domain")"
    if ! compose run --rm -T certbot "${args[@]}" >&2; then
        warn "$(t certs.failed "$domain")"
        info "$(t certs.hint1 "$domain")"
        info "$(t certs.hint2)"
        info "$(t certs.hint3)"
        info "$(t certs.retry)"
        return 1
    fi
    ok "$(t certs.issued "$domain")"
}

# issue_certificate: Let's Encrypt for DOMAIN of .env, then nginx is reloaded
# with it. Returns 1 with a hint on failure; callers carry on.
issue_certificate() {
    certbot_issue "$(site_domain)" || return 1
    render_nginx_conf
    render_ext_servers
    if nginx_reload; then
        ok "$(t certs.reloaded)"
    else
        warn "$(t certs.reload_fail)"
        return 1
    fi
}

# ext_cert_list: the registered extension certificates, "<id> <name>" per line.
ext_cert_list() {
    [[ -f "$EXT_CERTS_FILE" ]] || return 0
    grep -E '^[a-z0-9][a-z0-9_-]* [A-Za-z0-9.-]+$' "$EXT_CERTS_FILE" || true
}

# ext_cert_domain ID: the name registered by ID (empty when none).
ext_cert_domain() {
    ext_cert_list | awk -v id="$1" '$1 == id {print $2; exit}'
}

# _ext_cert_set ID [NAME]: register NAME for ID (one name per id), or drop the
# entry of ID when NAME is empty.
_ext_cert_set() {
    local id=$1 name=${2:-} tmp
    mkdir -p "$NGINX_DATA"
    tmp="$(mktemp "$EXT_CERTS_FILE.XXXXXX")"
    {
        printf '# Generated by install.sh (ext_cert_request): "<extension id> <name>" per line.\n'
        ext_cert_list | awk -v id="$id" '$1 != id'
        [[ -z "$name" ]] || printf '%s %s\n' "$id" "$name"
    } >"$tmp"
    chmod 644 "$tmp"
    mv -f "$tmp" "$EXT_CERTS_FILE"
}

# ext_cert_paths NAME: "CERT KEY", the paths inside the nginx container for a
# server block of NAME: the Let's Encrypt certificate when it exists, else the
# temporary self-signed one of NAME (created when missing).
ext_cert_paths() {
    local name=$1
    if have_le_cert "$name"; then
        printf '/etc/letsencrypt/live/%s/fullchain.pem /etc/letsencrypt/live/%s/privkey.pem\n' "$name" "$name"
        return 0
    fi
    ensure_selfsigned "$name" "$NGINX_DATA/selfsigned/$name"
    printf '/etc/nginx/selfsigned/%s/fullchain.pem /etc/nginx/selfsigned/%s/privkey.pem\n' "$name" "$name"
}

# ext_cert_request ID NAME: register NAME as a certificate of extension ID and
# obtain it from Let's Encrypt (unless it exists already); the server blocks of
# servers.d are then rendered again and nginx reloaded. NAME equal to DOMAIN of
# .env needs nothing (the base certificate). Returns 1 when the certificate could
# not be issued (with hints); the name stays registered, so `renew` (the timer)
# tries again. Never fatal for the caller.
ext_cert_request() {
    local id=${1:-} name=${2:-}
    ext_valid_id "$id" || die "$(t ext.bad_id ext_cert_request "$id")"
    valid_domain "$name" || die "$(t certs.ext_bad_name ext_cert_request "$name")"
    name="${name,,}"
    [[ "$name" != "$(site_domain)" ]] || return 0
    _ext_cert_set "$id" "$name"
    ok "$(t certs.ext_registered "$name" "$id")"
    if have_le_cert "$name"; then
        ok "$(t certs.ext_have "$name")"
    elif ! certbot_issue "$name"; then
        return 1
    fi
    render_ext_servers
    ext_nginx_apply || {
        warn "$(t certs.reload_fail)"
        return 1
    }
}

# ext_cert_release ID [--delete]: drop the registration of ID (no more renewals).
# The certificate files are kept (a reinstall uses them) unless --delete: then
# they are deleted, together with the self-signed one of the name. The base
# certificate (DOMAIN) and a name still registered by another id are never deleted.
ext_cert_release() {
    local id=${1:-} del=${2:-} name
    ext_valid_id "$id" || die "$(t ext.bad_id ext_cert_release "$id")"
    name="$(ext_cert_domain "$id")"
    [[ -n "$name" ]] || return 0
    _ext_cert_set "$id" ""
    ok "$(t certs.ext_released "$name" "$id")"
    [[ "$del" == --delete ]] || return 0
    [[ "$name" != "$(env_value DOMAIN)" ]] || return 0
    ext_cert_list | awk -v n="$name" '$2 == n {found = 1} END {exit !found}' && return 0
    if [[ -d "$LE_DIR/renewal" || -d "$LE_DIR/live/$name" ]]; then
        compose run --rm -T certbot delete --cert-name "$name" --non-interactive >/dev/null 2>&1 ||
            rm -rf "${LE_DIR:?}/live/$name" "${LE_DIR:?}/archive/$name" "${LE_DIR:?}/renewal/$name.conf"
    fi
    rm -rf "${NGINX_DATA:?}/selfsigned/$name"
    ok "$(t certs.ext_deleted "$name")"
}

# renew_certificates: the work of the timer: renew the certificate of DOMAIN and
# the registered extension certificates (the missing ones are issued), then
# render the configs and reload nginx. A failure of one name does not stop the
# others; nginx is reloaded in any case.
renew_certificates() {
    local domain rc=0 id name
    local -a names=()
    domain="$(site_domain)"
    if ! have_le_cert "$domain"; then
        certbot_issue "$domain" || rc=1
    fi
    have_le_cert "$domain" && names+=("$domain")
    while read -r id name; do
        [[ -n "$name" && "$name" != "$domain" ]] || continue
        if have_le_cert "$name"; then
            names+=("$name")
        else
            certbot_issue "$name" || rc=1
        fi
    done < <(ext_cert_list)
    for name in "${names[@]}"; do
        compose run --rm -T certbot renew --quiet --cert-name "$name" >&2 || {
            warn "$(t certs.renew_fail_name "$name")"
            rc=1
        }
    done
    render_nginx_conf
    render_ext_servers
    nginx_reload || {
        warn "$(t certs.renew_reload_fail)"
        return 1
    }
    ((rc == 0)) || return 1
    ok "$(t certs.renewed)"
}

# install_renew_timer: systemd timer (twice a day) running `install.sh renew`;
# /etc/cron.d entry when systemd is not running.
install_renew_timer() {
    local script="$APP_DIR/install.sh"
    if [[ -d /run/systemd/system ]]; then
        cat >"/etc/systemd/system/$RENEW_UNIT.service" <<UNIT
[Unit]
Description=Renew Let's Encrypt certificates of the fakeapp stack
After=docker.service
Wants=docker.service

[Service]
Type=oneshot
ExecStart="$script" renew
UNIT
        cat >"/etc/systemd/system/$RENEW_UNIT.timer" <<UNIT
[Unit]
Description=Renew Let's Encrypt certificates of the fakeapp stack twice a day

[Timer]
OnCalendar=*-*-* 03,15:17:00
RandomizedDelaySec=1h
Persistent=true

[Install]
WantedBy=timers.target
UNIT
        systemctl daemon-reload
        if systemctl enable --now "$RENEW_UNIT.timer" >/dev/null 2>&1; then
            ok "$(t certs.timer_ok "$RENEW_UNIT.timer" "$RENEW_UNIT.timer")"
            rm -f "$RENEW_CRON"
            return 0
        fi
        warn "$(t certs.timer_fail "$RENEW_UNIT.timer" "$RENEW_CRON")"
    fi
    printf '# Renew Let'"'"'s Encrypt certificates of the fakeapp stack (installed by install.sh).\n17 3,15 * * * root "%s" renew >/dev/null 2>&1\n' "$script" >"$RENEW_CRON"
    chmod 644 "$RENEW_CRON"
    ok "$(t certs.cron_ok "$RENEW_CRON")"
}

# remove_renew_timer: remove the systemd timer and the cron entry.
remove_renew_timer() {
    if [[ -f "/etc/systemd/system/$RENEW_UNIT.timer" ]]; then
        systemctl disable --now "$RENEW_UNIT.timer" >/dev/null 2>&1 || true
    fi
    rm -f "/etc/systemd/system/$RENEW_UNIT.timer" "/etc/systemd/system/$RENEW_UNIT.service" "$RENEW_CRON"
    [[ ! -d /run/systemd/system ]] || systemctl daemon-reload 2>/dev/null || true
}

renew_timer_state() {
    if [[ -f "/etc/systemd/system/$RENEW_UNIT.timer" ]]; then
        t certs.state_timer "$RENEW_UNIT.timer" "$(systemctl is-active "$RENEW_UNIT.timer" 2>/dev/null || true)"
    elif [[ -f "$RENEW_CRON" ]]; then
        t certs.state_cron "$RENEW_CRON"
    else
        t certs.state_none
    fi
}

# cert_summary: one line about the certificate nginx serves.
cert_summary() {
    local domain f end
    domain="$(site_domain)"
    if have_le_cert "$domain"; then
        end="$(openssl x509 -in "$LE_DIR/live/$domain/fullchain.pem" -noout -enddate 2>/dev/null | sed 's/^notAfter=//' || true)"
        t certs.sum_le "$([[ "$(env_or_default LE_STAGING 0)" != 1 ]] || t certs.staging_suffix)" "${end:-$(t certs.unknown)}"
    else
        t certs.sum_self
    fi
}

# validate_domain_dns: phase 2: DOMAIN should resolve to this host, or Let's
# Encrypt cannot validate it. Only warnings: DNS may still be propagating, or
# the host sits behind NAT; the install continues with a self-signed certificate.
validate_domain_dns() {
    check_domain_dns "$(env_value DOMAIN)"
}

# check_domain_dns NAME: the check of validate_domain_dns for any name (also
# used by extensions for their own names). Warnings only.
check_domain_dns() {
    local domain=$1 addrs local_addrs a
    valid_domain "$domain" || return 0
    addrs="$(getent ahostsv4 "$domain" 2>/dev/null | awk '{print $1}' | sort -u || true)"
    if [[ -z "$addrs" ]]; then
        warn "$(t certs.dns_noresolve "$domain")"
        return 0
    fi
    command -v ip >/dev/null 2>&1 || return 0
    local_addrs="$(ip -4 -o addr show 2>/dev/null | awk '{print $4}' | cut -d/ -f1 || true)"
    for a in $addrs; do
        grep -qxF "$a" <<<"$local_addrs" && {
            ok "$(t certs.dns_ok "$domain" "$a")"
            return 0
        }
    done
    addrs="$(tr '\n' ' ' <<<"$addrs")"
    warn "$(t certs.dns_mismatch "$domain" "${addrs% }")"
}
