# lib/extensions.sh - the extension framework and the ext_* helpers for files in extensions.d/.
# Sourced by install.sh (see the source list there): functions and variable
# defaults only, nothing runs at source time.
# shellcheck shell=bash
#
# Each extension is one file extensions.d/<NN>-<id>.sh (see extensions.d/README.md).
# Files are only added, never edited here, so branches adding extensions do not
# conflict on merge. A file calls: register_extension ID "Title" INSTALL_FN.
# Helpers for extension files (documented in extensions.d/README.md):
#   ext_register_compose ID FILE / ext_unregister_compose ID
#   ext_nginx_location_put ID (content on stdin) / ext_nginx_location_rm ID
#   ext_nginx_server_put ID [CERT_NAME] (content on stdin) / ext_nginx_server_rm ID
#   ext_cert_request ID NAME / ext_cert_release ID [--delete] / ext_cert_paths NAME (lib/certs.sh)
#   ext_domain, ext_compose
# Optional hooks per extension (install phases, see cmd_install): the functions
# ext_<id>_collect (all questions; changes nothing) and ext_<id>_validate (read-only
# checks, report with `problem`) and ext_<id>_purge (`remove --purge`: delete what
# the extension created outside the install directory); <id> has "-" written as
# "_". The install function registered here runs in the deploy phase and must not
# ask anything.

EXT_IDS=()
declare -A EXT_TITLE=() EXT_FN=()
EXT_SELECTED=""

# ext_valid_id ID: an identifier usable as a file name and a compose key.
ext_valid_id() { [[ "${1:-}" =~ ^[a-z0-9][a-z0-9_-]*$ ]]; }

# ext_compose ARGS...: the project's docker compose wrapper (all included files).
ext_compose() { compose "$@"; }

# ext_domain: DOMAIN of .env.
ext_domain() { env_get "$APP_DIR/.env" DOMAIN; }

# _ext_compose_rewrite ID PATH: set (PATH non-empty) or drop (PATH empty) the
# entry of ID in data/extensions.compose.yml, keeping the other entries.
# File format: `services: {}` when empty, else an `include:` list of lines
#   - "/absolute/path/to/compose.yml" # <id>
_ext_compose_rewrite() {
    local id=$1 path=$2 line i tmp
    local -a ids=() paths=()
    if [[ -f "$EXT_COMPOSE_FILE" ]]; then
        while IFS= read -r line || [[ -n "$line" ]]; do
            if [[ "$line" =~ ^[[:space:]]*-[[:space:]]+\"(.*)\"[[:space:]]+#[[:space:]]+([a-z0-9][a-z0-9_-]*)$ ]]; then
                [[ "${BASH_REMATCH[2]}" != "$id" ]] || continue
                paths+=("${BASH_REMATCH[1]}")
                ids+=("${BASH_REMATCH[2]}")
            fi
        done <"$EXT_COMPOSE_FILE"
    fi
    if [[ -n "$path" ]]; then
        ids+=("$id")
        paths+=("$path")
    fi
    mkdir -p "$DATA_DIR"
    tmp="$(mktemp "$EXT_COMPOSE_FILE.XXXXXX")"
    if ((${#ids[@]})); then
        {
            printf '# Generated by install.sh (ext_register_compose): do not edit.\ninclude:\n'
            for i in "${!ids[@]}"; do
                printf '  - "%s" # %s\n' "${paths[i]}" "${ids[i]}"
            done
        } >"$tmp"
    else
        printf 'services: {}\n' >"$tmp"
    fi
    chmod 644 "$tmp"
    if [[ $EUID -eq 0 ]]; then chown "$(project_owner)" "$tmp" 2>/dev/null || true; fi
    mv -f "$tmp" "$EXT_COMPOSE_FILE"
}

# ext_register_compose ID FILE: include the compose file FILE (an extension's
# services) in the stack: data/extensions.compose.yml is rewritten.
ext_register_compose() {
    local id=${1:-} file=${2:-}
    ext_valid_id "$id" || die "$(t ext.bad_id ext_register_compose "$id")"
    [[ -f "$file" ]] || die "$(t ext.compose_not_found ext_register_compose "$file")"
    file="$(realpath "$file")"
    [[ "$file" != *[\"$'\n']* ]] || die "$(t ext.bad_chars ext_register_compose "$file")"
    _ext_compose_rewrite "$id" "$file"
    ok "$(t ext.compose_registered "$id" "$file")"
}

# ext_unregister_compose ID: drop the entry of ID (stop its containers first).
ext_unregister_compose() {
    local id=${1:-}
    ext_valid_id "$id" || die "$(t ext.bad_id ext_unregister_compose "$id")"
    _ext_compose_rewrite "$id" ""
    ok "$(t ext.compose_unregistered "$id")"
}

# ext_nginx_location_put ID: write stdin to data/nginx/locations.d/<ID>.conf (a
# location block, included in the 443 server before `location /`), then test
# the config and reload nginx when it runs. A rejected config is rolled back.
ext_nginx_location_put() {
    local id=${1:-} dir="$NGINX_DATA/locations.d" file tmp backup=""
    ext_valid_id "$id" || die "$(t ext.bad_id ext_nginx_location_put "$id")"
    file="$dir/$id.conf"
    mkdir -p "$dir"
    tmp="$(mktemp "$file.XXXXXX")"
    cat >"$tmp"
    [[ -s "$tmp" ]] || { rm -f "$tmp"; die "$(t ext.empty_location ext_nginx_location_put "$id")"; }
    chmod 644 "$tmp"
    if [[ -f "$file" ]]; then
        backup="$(mktemp "$file.bak.XXXXXX")"
        cp -p "$file" "$backup"
    fi
    mv -f "$tmp" "$file"
    if ext_nginx_apply; then
        [[ -z "$backup" ]] || rm -f "$backup"
        ok "$(t ext.location_ok "$id" "$file")"
        return 0
    fi
    if [[ -n "$backup" ]]; then mv -f "$backup" "$file"; else rm -f "$file"; fi
    die "$(t ext.nginx_rejected "$id")"
}

# ext_nginx_location_rm ID: delete data/nginx/locations.d/<ID>.conf and reload.
ext_nginx_location_rm() {
    local id=${1:-}
    ext_valid_id "$id" || die "$(t ext.bad_id ext_nginx_location_rm "$id")"
    rm -f "$NGINX_DATA/locations.d/$id.conf"
    ext_nginx_apply || warn "$(t ext.nginx_after_rm "$id")"
    ok "$(t ext.location_removed "$id")"
}

# _ext_nginx_servers_ready: the base config includes servers.d and the running
# nginx container has the directory mounted. An installation made before
# servers.d existed is migrated here: the base config is rendered again and the
# nginx container recreated with the current compose file (a short restart).
_ext_nginx_servers_ready() {
    mkdir -p "$NGINX_DATA/servers.d"
    chmod a+rX "$NGINX_DATA/servers.d" 2>/dev/null || true
    grep -qF '/etc/nginx/servers.d/' "$NGINX_DATA/conf.d/default.conf" 2>/dev/null || render_nginx_conf
    stack_running nginx || return 0
    compose exec -T nginx test -d /etc/nginx/servers.d >/dev/null 2>&1 && return 0
    info "$(t ext.nginx_recreate)"
    compose up -d --wait nginx </dev/null >&2
}

# ext_nginx_server_put ID [CERT_NAME]: read whole server blocks (http level) from
# stdin into data/nginx/servers.d/<ID>.conf.in and render <ID>.conf from it. With
# CERT_NAME, @SSL_CERT@ and @SSL_KEY@ are replaced by the certificate of that
# name (Let's Encrypt when issued, else a temporary self-signed one; see
# ext_cert_request), also on every later render (renew, start, restart). Then
# the config is tested and nginx reloaded when it runs; a rejected config is
# rolled back and the script stops with an error.
ext_nginx_server_put() {
    local id=${1:-} name=${2:-} dir="$NGINX_DATA/servers.d" src out tmp b_src="" b_out=""
    ext_valid_id "$id" || die "$(t ext.bad_id ext_nginx_server_put "$id")"
    [[ -z "$name" ]] || valid_domain "$name" || die "$(t certs.ext_bad_name ext_nginx_server_put "$name")"
    src="$dir/$id.conf.in"
    out="$dir/$id.conf"
    mkdir -p "$dir"
    tmp="$(mktemp "$src.XXXXXX")"
    {
        [[ -z "$name" ]] || printf '# cert-domain: %s\n' "${name,,}"
        cat
    } >"$tmp"
    grep -qv '^# cert-domain: ' "$tmp" || { rm -f "$tmp"; die "$(t ext.empty_server ext_nginx_server_put "$id")"; }
    chmod 644 "$tmp"
    _ext_nginx_servers_ready </dev/null
    if [[ -f "$src" ]]; then b_src="$(mktemp "$src.bak.XXXXXX")" && cp -p "$src" "$b_src"; fi
    if [[ -f "$out" ]]; then b_out="$(mktemp "$out.bak.XXXXXX")" && cp -p "$out" "$b_out"; fi
    mv -f "$tmp" "$src"
    render_ext_servers
    if ext_nginx_apply; then
        [[ -z "$b_src" ]] || rm -f "$b_src"
        [[ -z "$b_out" ]] || rm -f "$b_out"
        ok "$(t ext.server_ok "$id" "$out")"
        return 0
    fi
    if [[ -n "$b_src" ]]; then mv -f "$b_src" "$src"; else rm -f "$src"; fi
    if [[ -n "$b_out" ]]; then mv -f "$b_out" "$out"; else rm -f "$out"; fi
    die "$(t ext.nginx_rejected_server "$id")"
}

# ext_nginx_server_rm ID: delete data/nginx/servers.d/<ID>.conf(.in) and reload.
ext_nginx_server_rm() {
    local id=${1:-}
    ext_valid_id "$id" || die "$(t ext.bad_id ext_nginx_server_rm "$id")"
    [[ -e "$NGINX_DATA/servers.d/$id.conf" || -e "$NGINX_DATA/servers.d/$id.conf.in" ]] || return 0
    rm -f "$NGINX_DATA/servers.d/$id.conf" "$NGINX_DATA/servers.d/$id.conf.in"
    ext_nginx_apply || warn "$(t ext.nginx_after_rm "$id")"
    ok "$(t ext.server_removed "$id")"
}

# ext_nginx_apply: `nginx -t` and reload when the nginx container runs (else
# the files are picked up at its next start). Fails when the test fails.
ext_nginx_apply() {
    if ! stack_running nginx; then
        info "$(t ext.nginx_not_running)"
        return 0
    fi
    compose exec -T nginx nginx -t >&2 || return 1
    compose exec -T nginx nginx -s reload >&2
}

register_extension() {
    local id=$1
    [[ "$id" =~ ^[a-z0-9][a-z0-9_-]*$ ]] || die "$(t ext.bad_id register_extension "$id")"
    EXT_IDS+=("$id")
    EXT_TITLE[$id]=$2
    EXT_FN[$id]=$3
}

load_extensions() {
    local f
    for f in "$CODE_DIR"/extensions.d/*.sh; do
        [[ -f "$f" ]] || continue
        # shellcheck disable=SC1090
        source "$f"
    done
}

# select_extensions: fill EXT_SELECTED (space separated ids) from --with /
# FAKEAPP_EXTENSIONS ("all" allowed) or an interactive menu.
select_extensions() {
    local want="${WITH_EXT:-${FAKEAPP_EXTENSIONS:-}}" id i ans
    EXT_SELECTED=""
    ((${#EXT_IDS[@]})) || return 0
    if [[ -n "$want" ]]; then
        want="${want//,/ }"
        if [[ "$want" == all ]]; then
            EXT_SELECTED="${EXT_IDS[*]}"
            return 0
        fi
        for id in $want; do
            [[ -n "${EXT_FN[$id]:-}" ]] || die "$(t ext.unknown "$id")"
        done
        EXT_SELECTED="$want"
        return 0
    fi
    [[ -t 0 && ! $ASSUME_YES -eq 1 ]] || return 0
    printf '\n%s\n' "$(t ext.menu_title)" >&2
    for i in "${!EXT_IDS[@]}"; do
        printf '  %d) %s\n' $((i + 1)) "$(ext_title "${EXT_IDS[i]}")" >&2
    done
    read -r -p "$(t ext.menu_prompt)" ans || return 0
    [[ -n "$ans" ]] || return 0
    if [[ "${ans,,}" == all ]]; then
        EXT_SELECTED="${EXT_IDS[*]}"
        return 0
    fi
    for i in ${ans//,/ }; do
        [[ "$i" =~ ^[0-9]+$ && -n "${EXT_IDS[i - 1]:-}" ]] || die "$(t ext.bad_choice "$i")"
        EXT_SELECTED+=" ${EXT_IDS[i - 1]}"
    done
}

run_extensions() {
    local id
    for id in $EXT_SELECTED; do
        step "$(t ext.step "$(ext_title "$id")")"
        "${EXT_FN[$id]}"
    done
}

# ext_hook ID NAME: the optional hook function ext_<id>_<name> (collect or
# validate; "-" in the id becomes "_"), printed when it is defined.
ext_hook() {
    local fn="ext_${1//-/_}_$2"
    declare -F "$fn" >/dev/null || return 0
    printf '%s' "$fn"
}

# collect_extensions: phase 1: the choice of extensions (select_extensions),
# then the questions of every selected extension that has a collect hook. Asks
# only; nothing is deployed or changed.
collect_extensions() {
    local id hook
    select_extensions
    for id in $EXT_SELECTED; do
        hook="$(ext_hook "$id" collect)"
        [[ -n "$hook" ]] || continue
        printf '\n%s\n' "${C_BOLD}$(ext_title "$id")${C_RESET}" >&2
        "$hook"
    done
}

# validate_extensions: phase 2: the validate hooks of the selected extensions.
# A hook records problems with `problem` (and may warn); it must not change anything.
validate_extensions() {
    local id hook
    for id in $EXT_SELECTED; do
        hook="$(ext_hook "$id" validate)"
        [[ -n "$hook" ]] || continue
        "$hook" || problem "$(t ext.validate_failed "$id")"
    done
}
